var GIFT_DEBUG_PREFIX = "[GiftSend Debug]";

function giftToInt(value, fallback) {
  var numeric = parseInt(value, 10);
  return isNaN(numeric) ? fallback : numeric;
}

function giftNormalizeString(value, fallback) {
  if (value === null || value === undefined) return fallback || "";
  var text = String(value);
  return text ? text : (fallback || "");
}

function giftDebugLog(scope, payload) {
  try {
    console.log(GIFT_DEBUG_PREFIX + "[" + scope + "] " + JSON.stringify(payload));
  } catch (error) {
    console.log(GIFT_DEBUG_PREFIX + "[" + scope + "] " + String(payload));
  }
}

function giftIsByteArrayLike(value) {
  if (!value) return false;
  if (typeof Uint8Array !== "undefined" && value instanceof Uint8Array) return true;
  if (!Array.isArray(value)) return false;
  for (var i = 0; i < value.length; i++) {
    var item = value[i];
    if (typeof item !== "number" || !isFinite(item) || item < 0 || item > 255) {
      return false;
    }
  }
  return true;
}

function giftDecodeUtf8Bytes(value) {
  if (!value) return "";
  if (typeof value === "string") return value;
  try {
    var bytes = value;
    if (Array.isArray(value)) {
      if (typeof Uint8Array !== "undefined") {
        bytes = Uint8Array.from(value);
      }
    }
    if (typeof TextDecoder !== "undefined") {
      return new TextDecoder("utf-8").decode(bytes);
    }
  } catch (error) {
    // Pure JS UTF-8 decoder fallback below.
  }

  var raw = Array.isArray(value) ? value : Array.prototype.slice.call(value || []);
  var out = "";
  var i = 0;
  var len = raw.length;
  while (i < len) {
    var c = raw[i++] & 0xff;
    if ((c & 0x80) === 0) {
      out += String.fromCharCode(c);
    } else if ((c & 0xe0) === 0xc0) {
      if (i < len) {
        var c2 = raw[i++] & 0xff;
        out += String.fromCharCode(((c & 0x1f) << 6) | (c2 & 0x3f));
      }
    } else if ((c & 0xf0) === 0xe0) {
      if (i + 1 < len) {
        var c2 = raw[i++] & 0xff;
        var c3 = raw[i++] & 0xff;
        out += String.fromCharCode(((c & 0x0f) << 12) | ((c2 & 0x3f) << 6) | (c3 & 0x3f));
      }
    } else if ((c & 0xf8) === 0xf0) {
      if (i + 2 < len) {
        var c2 = raw[i++] & 0xff;
        var c3 = raw[i++] & 0xff;
        var c4 = raw[i++] & 0xff;
        var cp = (((c & 0x07) << 18) | ((c2 & 0x3f) << 12) | ((c3 & 0x3f) << 6) | (c4 & 0x3f)) - 0x10000;
        out += String.fromCharCode(0xd800 + (cp >> 10), 0xdc00 + (cp & 0x3ff));
      }
    } else {
      out += String.fromCharCode(c);
    }
  }
  return out;
}

// PocketBase JSON columns can arrive as byte arrays, strings, or objects —
// same defensive parsing as chest_server_utils.js / reputation-action.
function giftParseDataField(record) {
  if (!record) return {};
  var raw = record.get("data");
  if (!raw) return {};

  if (Array.isArray(raw) || giftIsByteArrayLike(raw)) {
    try {
      var decodedBytes = giftDecodeUtf8Bytes(raw);
      var parsedBytes = JSON.parse(decodedBytes);
      if (parsedBytes && typeof parsedBytes === "object" && !Array.isArray(parsedBytes)) {
        return parsedBytes;
      }
      return {};
    } catch (error) {
      return {};
    }
  }

  if (typeof raw === "string") {
    try {
      var parsedString = JSON.parse(raw);
      if (parsedString && typeof parsedString === "object" && !Array.isArray(parsedString)) {
        return parsedString;
      }
      return {};
    } catch (error) {
      return {};
    }
  }

  if (typeof raw === "object" && !Array.isArray(raw)) {
    return raw;
  }

  return {};
}

function giftSetDataField(record, obj) {
  record.set("data", JSON.stringify(obj));
}

function giftParseInventoryField(record) {
  if (!record) return {};
  var raw = record.get("inventory");
  if (!raw) return {};

  if (Array.isArray(raw) || giftIsByteArrayLike(raw)) {
    try {
      var parsedBytes = JSON.parse(giftDecodeUtf8Bytes(raw));
      if (parsedBytes && typeof parsedBytes === "object" && !Array.isArray(parsedBytes)) {
        return parsedBytes;
      }
      return {};
    } catch (error) {
      return {};
    }
  }

  if (typeof raw === "string") {
    try {
      var parsedString = JSON.parse(raw);
      if (parsedString && typeof parsedString === "object" && !Array.isArray(parsedString)) {
        return parsedString;
      }
      return {};
    } catch (error) {
      return {};
    }
  }

  if (typeof raw === "object" && !Array.isArray(raw)) {
    return raw;
  }

  return {};
}

function giftBuildErrorResponse(status, errorCode, details, message) {
  return {
    status: status,
    body: {
      success: false,
      error: errorCode,
      message: giftNormalizeString(message, ""),
      details: details || null,
    },
  };
}

function giftResolveTargetRecord(txApp, targetId) {
  var targetRecord = null;
  try {
    targetRecord = txApp.findRecordById("users", targetId);
  } catch (_) {}
  if (!targetRecord) {
    try {
      var list = txApp.findRecordsByFilter(
        "users",
        "id = '" + targetId + "' || gameId = '" + targetId + "'",
        "-created",
        1
      );
      if (list && list.length > 0) {
        targetRecord = list[0];
      }
    } catch (_) {}
  }
  return targetRecord;
}

// Grant the gifted building into the recipient's inventory. Inventory is a
// merge-only JSON column (DATABASE_SCHEMA.md) — read current value, add 1,
// never overwrite the whole object blindly.
function giftGrantInventoryItem(targetRecord, buildingIdKey) {
  var inventory = giftParseInventoryField(targetRecord);
  var beforeAmount = Math.max(0, giftToInt(inventory[buildingIdKey] !== undefined ? inventory[buildingIdKey] : 0, 0));
  inventory[buildingIdKey] = beforeAmount + 1;
  targetRecord.set("inventory", JSON.stringify(inventory));
  return {
    beforeAmount: beforeAmount,
    afterAmount: inventory[buildingIdKey],
    inventory: inventory,
  };
}

function processGiftSend(app, authRecord, targetUserId, buildingId) {
  var result = null;

  try {
    if (!authRecord) {
      return giftBuildErrorResponse(401, "AUTH_REQUIRED", {}, "Authentication required");
    }

    var issuerId = authRecord.id;
    var issuerName = giftNormalizeString(authRecord.get("name"), "Игрок");
    var targetId = giftNormalizeString(targetUserId, "").trim();
    if (!targetId) {
      return giftBuildErrorResponse(400, "MISSING_TARGET", {}, "Recipient is required");
    }
    // Recipient ids are PocketBase record ids (users.gameId mirrors the record
    // id). Reject anything else before it reaches a filter string.
    if (!/^[A-Za-z0-9_-]{1,64}$/.test(targetId)) {
      return giftBuildErrorResponse(404, "TARGET_NOT_FOUND", {
        targetId: targetId.substring(0, 64),
      }, "Игрок-получатель не найден");
    }

    var buildingKey = giftNormalizeString(buildingId, "").trim();
    var catalogEntry = GIFT_BUILDING_CATALOG[buildingKey];
    if (!catalogEntry || !catalogEntry.rubyPrice) {
      return giftBuildErrorResponse(400, "INVALID_BUILDING", {
        buildingId: buildingKey,
      }, "Unknown gift building");
    }
    var buildingIdNumber = giftToInt(buildingKey, 0);
    var buildingName = giftNormalizeString(catalogEntry.name, "Подарок #" + buildingKey);
    var rubyPrice = giftToInt(catalogEntry.rubyPrice, 0);

    var nowMs = Date.now();

    app.runInTransaction(function (txApp) {
      var issuerRecord = txApp.findRecordById("users", issuerId);
      if (!issuerRecord) {
        throw new Error("ISSUER_NOT_FOUND");
      }

      var targetRecord = giftResolveTargetRecord(txApp, targetId);
      if (!targetRecord) {
        throw new Error("TARGET_NOT_FOUND");
      }

      var issuerEmail = giftNormalizeString(issuerRecord.get("email"), "");
      var isAdmin = issuerEmail === "fabiosluco@gmail.com";
      if (targetRecord.id === issuerId && !isAdmin) {
        throw new Error("CANNOT_GIFT_SELF");
      }

      // Debit the sender first: rubies are a non-negative server counter and
      // the data JSON mirror is kept in sync (punish-player pattern).
      var currentRubies = Math.max(0, giftToInt(issuerRecord.get("rubies"), 0));
      if (currentRubies < rubyPrice) {
        throw new Error("INSUFFICIENT_RUBIES|" + rubyPrice + "|" + currentRubies);
      }
      var nextRubies = currentRubies - rubyPrice;
      issuerRecord.set("rubies", nextRubies);
      var issuerData = giftParseDataField(issuerRecord);
      issuerData.rubies = nextRubies;
      giftSetDataField(issuerRecord, issuerData);
      txApp.save(issuerRecord);

      // Grant the item to the recipient.
      var inventoryGrant = giftGrantInventoryItem(targetRecord, String(buildingKey));

      // Realtime notification payload for the recipient's users snapshot.
      var targetData = giftParseDataField(targetRecord);
      targetData.lastGiftNotification = {
        fromId: issuerId,
        fromName: issuerName,
        buildingId: buildingIdNumber,
        buildingName: buildingName,
        rubyPrice: rubyPrice,
        at: nowMs,
      };
      giftSetDataField(targetRecord, targetData);
      txApp.save(targetRecord);

      // History entry for the recipient (history has no data/gameId columns).
      var historyCollection = txApp.findCollectionByNameOrId("history");
      var historyRecord = new Record(historyCollection);
      historyRecord.set("userId", targetRecord.id);
      historyRecord.set("message", "Игрок " + issuerName + " подарил вам «" + buildingName + "»!");
      historyRecord.set("type", "social");
      historyRecord.set("timestamp", nowMs);
      txApp.save(historyRecord);

      result = {
        status: 200,
        body: {
          success: true,
          targetUserId: targetRecord.id,
          targetName: giftNormalizeString(targetRecord.get("name"), "Игрок"),
          buildingId: buildingIdNumber,
          buildingName: buildingName,
          rubyPrice: rubyPrice,
          senderRubies: nextRubies,
          senderName: issuerName,
          grantedCount: inventoryGrant.afterAmount,
          notificationAt: nowMs,
        },
      };

      giftDebugLog("transaction", {
        issuerId: issuerId,
        targetId: targetRecord.id,
        buildingId: buildingIdNumber,
        rubyPrice: rubyPrice,
        senderRubies: nextRubies,
      });
    });

    if (!result) {
      return giftBuildErrorResponse(500, "INTERNAL_ERROR", {}, "Gift transaction produced no result");
    }
    return result;
  } catch (error) {
    var detail = String(error);
    giftDebugLog("error", { detail: detail.substring(0, 300) });

    if (detail.indexOf("INSUFFICIENT_RUBIES") !== -1) {
      var required = 0;
      var available = 0;
      var parts = detail.split("|");
      if (parts.length >= 3) {
        required = giftToInt(parts[1], 0);
        available = giftToInt(parts[2], 0);
      }
      return giftBuildErrorResponse(409, "INSUFFICIENT_RUBIES", {
        required: required,
        available: available,
      }, "Недостаточно рубинов для подарка");
    }
    if (detail.indexOf("CANNOT_GIFT_SELF") !== -1) {
      return giftBuildErrorResponse(400, "CANNOT_GIFT_SELF", {}, "Нельзя подарить подарок самому себе");
    }
    if (detail.indexOf("TARGET_NOT_FOUND") !== -1 || detail.indexOf("ISSUER_NOT_FOUND") !== -1) {
      return giftBuildErrorResponse(404, "TARGET_NOT_FOUND", {}, "Игрок-получатель не найден");
    }
    return giftBuildErrorResponse(500, "INTERNAL_ERROR", {
      detail: detail.substring(0, 200),
    }, "Не удалось отправить подарок");
  }
}

